def prompt_of(body):
    return json.dumps(
        {
            "system": body.get("system", ""),
            "tools": body.get("tools", []),
            "messages": body.get("messages", []),
        },
        sort_keys=True,
    )


def conversation_of(body):
    return json.dumps(
        [m for m in body.get("messages", []) if m.get("role") not in ("system", "developer")],
        sort_keys=True,
    )


def spoken(body):
    texts = []
    for message in body.get("messages", []):
        if message.get("role") != "user":
            continue
        content = message.get("content")
        if isinstance(content, str):
            texts.append(content)
        elif isinstance(content, list):
            for block in content:
                if isinstance(block, dict) and block.get("type") == "text":
                    texts.append(block.get("text", ""))
                elif isinstance(block, dict) and block.get("type") == "tool_result":
                    inner = block.get("content")
                    texts.append(inner if isinstance(inner, str) else json.dumps(inner))
    return "\n".join(texts)


def response_of(out):
    if "choices" in out:
        message = (out["choices"] or [{}])[0].get("message", {})
        blocks = []
        if message.get("content"):
            blocks.append({"type": "text", "text": message["content"]})
        for call in message.get("tool_calls") or []:
            blocks.append(
                {
                    "type": "tool_use",
                    "name": call["function"]["name"],
                    "input": json.loads(call["function"].get("arguments") or "{}"),
                }
            )
        return blocks
    return strip_ids(out.get("content", []))


def offered_by(body):
    return {t.get("name") or (t.get("function") or {}).get("name") for t in body.get("tools", [])}


def pairs_of(response):
    pairs = []

    def walk(prefix, value):
        if isinstance(value, dict):
            for k in sorted(value):
                walk(f"{prefix}.{k}" if prefix else k, value[k])
        elif isinstance(value, list):
            for i, v in enumerate(value):
                walk(f"{prefix}[{i}]", v)
        else:
            pairs.append((prefix, json.dumps(value)))

    walk("", response)
    return pairs


def patterns_in(reply):
    found = [m.group(2) for m in re.finditer(r"r?(['\"])((?:\\.|(?!\1).)*)\1", reply)]
    found.sort(key=len, reverse=True)
    return found + [reply]


def fenced(text):
    match = re.search(r"```(?:python)?\n(.*?)```", text, re.DOTALL)
    return match.group(1) if match else text


class Cluster:
    def __init__(self, prompt_vector, response_vectors):
        self.prompt_centroid = list(prompt_vector)
        self.response_centroids = [list(v) for v in response_vectors]
        self.count = 0
        self.examples = []
        self.said = []
        self.compiled = None
        self.attempts = 0
        self.generation_failed = False
        self.generating = False
        self.settled = threading.Event()
        self.settled.set()

    def add(self, prompt, response, prompt_vector, response_vectors, said=""):
        n = self.count
        self.prompt_centroid = [
            (c * n + v) / (n + 1) for c, v in zip(self.prompt_centroid, prompt_vector)
        ]
        self.response_centroids = [
            [(c * n + v) / (n + 1) for c, v in zip(centroid, vector)]
            for centroid, vector in zip(self.response_centroids, response_vectors)
        ]
        self.count = n + 1
        self.examples.append((prompt, response))
        self.said.append(said)


class Synthesis:
    """The program writer: an OpenAI-compatible model, through OpenRouter when the model name
    carries a provider prefix. Every call is priced and can be logged."""

    def __init__(self, cell_index=0):
        import httpx
        import openai

        self.cell_index = cell_index
        fresh = httpx.Client(
            timeout=CALL_SECONDS,
            limits=httpx.Limits(max_keepalive_connections=0, max_connections=8),
        )
        if "/" in MODEL:
            self.client = openai.OpenAI(
                base_url="https://openrouter.ai/api/v1",
                api_key=os.environ["OPENROUTER_API_KEY"],
                timeout=CALL_SECONDS,
                max_retries=2,
                http_client=fresh,
            )
        else:
            self.client = openai.OpenAI(timeout=CALL_SECONDS, max_retries=2, http_client=fresh)
        self.ask = self.ask_openai
        self.calls = 0
        self.dollars = 0.0

    def ask_openai(self, role, text, suffix=""):
        started = time.time()
        response = self.client.chat.completions.create(
            model=MODEL,
            messages=[{"role": "user", "content": text + suffix}],
            extra_body={"reasoning": {"effort": EFFORT}} if EFFORT else {},
        )
        answer = response.choices[0].message.content or ""
        usage = response.usage
        details = getattr(usage, "prompt_tokens_details", None)
        read = (getattr(details, "cached_tokens", 0) or 0) if details else 0
        return self.record(
            role,
            response.model,
            answer,
            usage.prompt_tokens - read,
            0,
            read,
            usage.completion_tokens,
            time.time() - started,
        )

    def record(self, role, model, answer, plain, written, read, output, seconds):
        cost = plain * PRICE_IN + written * PRICE_WRITE + read * PRICE_READ + output * PRICE_OUT
        self.calls += 1
        self.dollars += cost
        if LOG:
            with open(LOG, "a") as f:
                f.write(
                    json.dumps(
                        {
                            "at": time.time(),
                            "run": RUN,
                            "cell_index": self.cell_index,
                            "role": role,
                            "model": model,
                            "input_tokens": plain,
                            "cache_written": written,
                            "cache_read": read,
                            "output_tokens": output,
                            "seconds": round(seconds, 2),
                            "dollars": round(cost, 6),
                        }
                    )
                    + "\n"
                )
        return answer


def run_program(code, prompt):
    with tempfile.TemporaryDirectory() as work:
        path = os.path.join(work, "runnable_code.py")
        with open(path, "w") as f:
            f.write(code)
        try:
            done = subprocess.run(
                [sys.executable, "-I", path, prompt],
                capture_output=True,
                text=True,
                timeout=PROGRAM_SECONDS,
                cwd=work,
                env={},
            )
        except subprocess.TimeoutExpired:
            return None
    if done.returncode != 0:
        return None
    return done.stdout.strip()


def sane(output, body):
    if not output or output.startswith("None"):
        return None
    try:
        blocks = json.loads(output)
    except ValueError:
        return None
    if not isinstance(blocks, list) or not blocks:
        return None
    offered = offered_by(body)
    for block in blocks:
        if not isinstance(block, dict):
            return None
        if block.get("type") == "text":
            if not isinstance(block.get("text"), str):
                return None
        elif block.get("type") == "tool_use":
            if block.get("name") not in offered or not isinstance(block.get("input"), dict):
                return None
        else:
            return None
    return blocks


class GenCache(LocalServer):
    def __init__(self, port, upstream):
        super().__init__(("127.0.0.1", port), Handler)
        self.upstream = upstream
        self.embed = onnx_embedder()
        self.clusters = []
        global STARTED
        STARTED += 1
        self.synthesis = Synthesis(STARTED - 1)
        self.tool_ids = 0
        self.lock = threading.Lock()
        self.closing = False
        self.broken = None

    def shutdown(self):
        self.closing = True
        super().shutdown()

    def nearest(self, prompt_vector):
        best, score = None, T_P
        for cluster in self.clusters:
            sim = cosine(prompt_vector, cluster.prompt_centroid)
            if sim > score:
                best, score = cluster, sim
        return best

    def assign(self, prompt, response, prompt_vector, response_vectors, said=""):
        best, score = None, None
        for cluster in self.clusters:
            if len(cluster.response_centroids) != len(response_vectors):
                continue
            s_p = cosine(prompt_vector, cluster.prompt_centroid)
            if s_p <= T_P:
                continue
            s_r = sum(
                cosine(v, c) for v, c in zip(response_vectors, cluster.response_centroids)
            ) / len(response_vectors)
            if s_r <= T_R:
                continue
            if score is None or s_p + s_r > score:
                best, score = cluster, s_p + s_r
        if best is None:
            best = Cluster(prompt_vector, response_vectors)
            self.clusters.append(best)
        if best.count < 3 * NU:
            best.add(prompt, response, prompt_vector, response_vectors, said)
        return best

    def synthesise_later(self, cluster):
        with self.lock:
            if cluster.generating or cluster.generation_failed or cluster.compiled:
                return
            cluster.generating = True
            cluster.settled.clear()
        threading.Thread(target=self.generate, args=(cluster,), daemon=True).start()

    def generate(self, cluster, reflection=""):
        try:
            self.attempt(cluster, reflection)
        except Exception as error:
            self.broken = f"{type(error).__name__}: {str(error)[:200]}"
        finally:
            cluster.generating = False
            cluster.settled.set()

    def attempt(self, cluster, reflection):
        while cluster.compiled is None and cluster.attempts < RHO and not self.closing:
            cluster.attempts += 1
            cluster.settled.set()
            cluster.settled.clear()
            examples = "\n\n".join(
                f"Example {i + 1}:\nInput Prompt:\n{p}\nResponse:\n{json.dumps(r)}"
                for i, (p, r) in enumerate(cluster.examples)
            )
            code = fenced(
                self.synthesis.ask(
                    "codegen",
                    CODEGEN_PROMPT.format(examples=examples, suffix=""),
                    CODEGEN_SUFFIX.format(reflection=reflection),
                )
            )
            outputs = [run_program(code, p) for p, _ in cluster.examples]
            comparisons = "\n\n".join(
                f"Comparison {i + 1}:\nGround truth: {json.dumps(r)}\n"
                f"LLM-generated: {o if o is not None else 'None: the program failed'}"
                for i, ((_, r), o) in enumerate(zip(cluster.examples, outputs))
            )
            verdict = self.synthesis.ask("valid", VALID_PROMPT.format(comparisons=comparisons))
            try:
                parsed = json.loads(fenced(verdict).strip().strip("`"))
                valid = [int(v) for v in parsed["valid"]]
                reason = str(parsed.get("reason", ""))
            except (ValueError, KeyError, TypeError):
                valid, reason = [], "the validator's reply could not be read"
            if valid and sum(valid) >= GAMMA * len(cluster.examples):
                compiled_pattern = self.pattern_for(cluster)
                if compiled_pattern is None:
                    reason = "no pattern could be written that matches every example prompt"
                else:
                    cluster.compiled = (code, compiled_pattern)
                    return
            reflection = (
                "\nThe previous program you generated was:\n```python\n"
                f"{code}\n```\nIt was validated against the examples and failed. "
                f"The validator said: {reason}\nGenerate a corrected program."
            )
        if cluster.compiled is None and cluster.attempts >= RHO:
            cluster.generation_failed = True

    def pattern_for(self, cluster):
        for _ in range(3):
            reply = fenced(
                self.synthesis.ask("regex", REGEX_PROMPT.format(prompts="\n\n".join(cluster.said)))
            ).strip()
            for candidate in patterns_in(reply):
                try:
                    compiled_pattern = re.compile(candidate, re.DOTALL)
                except re.error:
                    continue
                if all(compiled_pattern.search(s) for s in cluster.said):
                    return compiled_pattern
        return None

    def serve_from(self, cluster, prompt, body):
        compiled = cluster.compiled
        if compiled is None:
            return None
        code, pattern = compiled
        if pattern is not None and not pattern.search(spoken(body)):
            return None
        blocks = sane(run_program(code, prompt), body)
        if blocks is None:
            with self.lock:
                if cluster.compiled is compiled:
                    cluster.compiled = None
            self.synthesise_later(cluster)
            return None
        for block in blocks:
            if block["type"] == "tool_use":
                self.tool_ids += 1
                block["id"] = f"gencache_{self.tool_ids}"
        calls = any(b["type"] == "tool_use" for b in blocks)
        if "system" not in body and any(
            m.get("role") == "system" for m in body.get("messages", [])
        ):
            return {
                "id": f"chatcmpl_gencache_{self.tool_ids}",
                "object": "chat.completion",
                "model": body.get("model", "stub"),
                "choices": [
                    {
                        "index": 0,
                        "finish_reason": "tool_calls" if calls else "stop",
                        "message": {
                            "role": "assistant",
                            "content": "".join(b["text"] for b in blocks if b["type"] == "text")
                            or None,
                            "tool_calls": [
                                {
                                    "id": b["id"],
                                    "type": "function",
                                    "function": {
                                        "name": b["name"],
                                        "arguments": json.dumps(b["input"]),
                                    },
                                }
                                for b in blocks
                                if b["type"] == "tool_use"
                            ]
                            or None,
                        },
                    }
                ],
                "usage": {"prompt_tokens": 0, "completion_tokens": 0},
            }
        return {
            "id": f"msg_gencache_{self.tool_ids}",
            "type": "message",
            "role": "assistant",
            "model": body.get("model", "stub"),
            "content": blocks,
            "stop_reason": "tool_use" if calls else "end_turn",
            "stop_sequence": None,
            "usage": {"input_tokens": 0, "output_tokens": 0},
        }


class Handler(ProxyHandler):
    def do_POST(self):
        raw = self.rfile.read(int(self.headers["Content-Length"]))
        body = json.loads(raw)
        server = self.server
        if server.broken:
            self.refuse(
                f"GenCache's synthesiser failed and the run is not a measurement: {server.broken}"
            )
            return
        prompt = prompt_of(body)
        prompt_vector = server.embed(conversation_of(body))
        cluster = server.nearest(prompt_vector)
        if cluster is not None:
            if cluster.compiled is None and cluster.generating:
                cluster.settled.wait(WAIT_SECONDS)
            out = server.serve_from(cluster, prompt, body)
            if out is not None:
                zero_usage(out)
                self.reply(out)
                return
        out = forward(server.upstream, raw, self.path)
        response = response_of(out)
        if response:
            response_vectors = [server.embed(value) for _, value in pairs_of(response)]
            landed = server.assign(prompt, response, prompt_vector, response_vectors, spoken(body))
            if landed.count >= NU:
                server.synthesise_later(landed)
        self.reply(out)

    def refuse(self, why):
        payload = json.dumps({"error": why}).encode()
        self.send_response(500)
        self.send_header("content-type", "application/json")
        self.send_header("content-length", str(len(payload)))
        self.end_headers()
        self.wfile.write(payload)
