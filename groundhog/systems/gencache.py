MODEL = os.environ.get("GROUNDHOG_GENCACHE_MODEL", "openai/gpt-5-mini")

NU = int(os.environ.get("GROUNDHOG_GENCACHE_NU", "4"))
GAMMA = 0.5
RHO = int(os.environ.get("GROUNDHOG_GENCACHE_RHO", "30"))
T_P = 0.8
T_R = 0.75

LOG = os.environ.get("GROUNDHOG_GENCACHE_LOG", "")
RUN = secrets.token_hex(6)
STARTED = 0

# Dollars per million tokens: input, output, cache write, cache read.
PRICES = {
    "gpt-4o": (2.5, 10.0, 2.5, 1.25),
    "gpt-4o-mini": (0.15, 0.6, 0.15, 0.075),
    "gpt-5-mini": (0.25, 2.0, 0.25, 0.025),
}
NAN = float("nan")
PRICE_IN, PRICE_OUT, PRICE_WRITE, PRICE_READ = (
    p / 1_000_000 for p in PRICES.get(MODEL.rpartition("/")[2], (NAN, NAN, NAN, NAN))
)

PROGRAM_SECONDS = 10

WAIT_SECONDS = 150

CALL_SECONDS = 120

EFFORT = os.environ.get("GROUNDHOG_GENCACHE_EFFORT", "low")

