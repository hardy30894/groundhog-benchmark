"""GenCache, a generative cache, written from its paper.

Requests are clustered by the similarity of their prompts and of their replies (thresholds
T_p = 0.8 and T_r = 0.75). Once a cluster holds nu = 4 examples, a model writes a Python
program that maps any request of the cluster's shape to its reply, the program is run on
the examples and kept if at least gamma = 50% come out right (up to rho = 30 attempts), and
a pattern is written that decides whether a later request belongs to the cluster. A
request that falls in a cluster with a program and matches its pattern is answered by
running the program instead of asking the model under test.

The program writer is a real model, so this system needs an API key and costs money: the
paper's run made 621 calls for about one dollar.

    OPENROUTER_API_KEY            for a model named provider/model, through OpenRouter
    GROUNDHOG_GENCACHE_MODEL      the program writer; openai/gpt-5-mini by default
    GROUNDHOG_GENCACHE_EFFORT     its reasoning effort; low by default
    GROUNDHOG_GENCACHE_NU         examples a cluster needs before a program is written; 4
    GROUNDHOG_GENCACHE_RHO        attempts at a program; 30
    GROUNDHOG_GENCACHE_LOG        a file to log every program-writer call and its price to
"""

import json
import os
